from pathlib import Path
root=Path(__file__).resolve().parents[1]
files=sorted(p for p in (root/'data').rglob('*') if p.is_file())
with (root/'src/embedded_assets.hpp').open('w') as f:
 f.write('// Generated by scripts/embed_assets.py.\nstruct EmbeddedAsset {const char *name; const unsigned char *bytes; size_t size;};\n')
 for i,p in enumerate(files):f.write('static const unsigned char asset_'+str(i)+'[]={'+','.join(map(str,p.read_bytes()))+'};\n')
 f.write('static const EmbeddedAsset embedded_assets[]={\n')
 for i,p in enumerate(files):f.write('{"'+p.relative_to(root/'data').as_posix()+'",asset_'+str(i)+',sizeof(asset_'+str(i)+')},\n')
 f.write('};\n')
